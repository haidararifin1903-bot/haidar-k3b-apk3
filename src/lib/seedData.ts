// Generate comprehensive yard locations: Block A, B, C, D
export function generateInitialYardLocations(): YardLocation[] {
  const blocks: ('Block A' | 'Block B' | 'Block C' | 'Block D')[] = [
    'Block A',
    'Block B',
    'Block C',
    'Block D',
  ];
  const locations: YardLocation[] = [];

  blocks.forEach((block) => {
    const blockLetter = block.split(' ')[1];
    // Each block has 4 rows, 6 bays, 3 tiers = 72 slots per block = 288 total terminal slots
    for (let r = 1; r <= 4; r++) {
      for (let b = 1; b <= 6; b++) {
        for (let t = 1; t <= 3; t++) {
          const rowStr = r.toString().padStart(2, '0');
          const bayStr = b.toString().padStart(2, '0');
          const location_code = `${blockLetter}-${rowStr}-${bayStr}-${t}`;
          locations.push({
            id: `loc-${blockLetter}-${rowStr}-${bayStr}-${t}`,
            block,
            row: r,
            bay: b,
            tier: t,
            location_code,
            status: 'Available',
            created_at: '2026-01-01T00:00:00Z',
          });
        }
      }
    }
  });

  return locations;
}

